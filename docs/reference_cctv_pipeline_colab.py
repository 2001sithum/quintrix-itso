def load_stage2_model(checkpoint_path, num_classes, device):
    model = r3d_18(weights=None)
    model.fc = nn.Linear(model.fc.in_features, num_classes)

    raw = torch.load(checkpoint_path, map_location=device)

    # figure out where the actual state_dict is hiding
    if isinstance(raw, dict) and any(k in raw for k in ('model_state_dict', 'state_dict')):
        state_dict = raw.get('model_state_dict', raw.get('state_dict'))
        print('Loaded from wrapped checkpoint dict. Keys present:', list(raw.keys()))
    elif isinstance(raw, dict):
        # looks like a raw state_dict already (keys are layer names)
        state_dict = raw
        print('Loaded as raw state_dict.')
    else:
        raise ValueError(f'Unrecognized checkpoint format: {type(raw)}')

    # strip a 'module.' prefix if the model was saved from nn.DataParallel
    state_dict = { (k[7:] if k.startswith('module.') else k): v for k, v in state_dict.items() }

    missing, unexpected = model.load_state_dict(state_dict, strict=False)
    if missing:
        print('WARNING - missing keys when loading:', missing)
    if unexpected:
        print('WARNING - unexpected keys when loading:', unexpected)

    model.to(device).eval()
    return model

