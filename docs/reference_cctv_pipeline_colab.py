"""## Step 5 - Frame sampling utilities

- Action recognition needs exactly **16 uniformly-spaced frames** per segment (matching Stage 2 training), resized/cropped to 112x112 and normalized with Kinetics stats.
- Object detection (Track 1 and Track 2) samples **1 frame per second** within the segment - running YOLO on every single frame is unnecessary and slow; suspicious objects/context don't change that fast.
"""

import numpy as np
import torch.nn.functional as F

# Kinetics-400 normalization stats (matches Stage 2 training preprocessing)
KINETICS_MEAN = [0.43216, 0.394666, 0.37645]
KINETICS_STD = [0.22803, 0.22145, 0.216989]

def read_frames(video_path, frame_indices):
    cap = cv2.VideoCapture(video_path)
    frames = {}
    for idx in sorted(set(frame_indices)):
        cap.set(cv2.CAP_PROP_POS_FRAMES, idx)
        ok, frame = cap.read()
        if ok:
            frames[idx] = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
    cap.release()
    return frames

def sample_action_recognition_clip(video_path, start_frame, end_frame, num_frames=16):
    indices = np.linspace(start_frame, end_frame - 1, num_frames).astype(int)
    frames = read_frames(video_path, indices)
    clip = []
    for idx in indices:
        frame = frames.get(idx)
        if frame is None:
            continue
        frame = cv2.resize(frame, (128, 128))
        h, w, _ = frame.shape
        top, left = (h - 112) // 2, (w - 112) // 2
        frame = frame[top:top + 112, left:left + 112]
        clip.append(frame)
    if len(clip) < num_frames:
        # pad by repeating the last available frame (rare - only if reads failed near the end)
        while len(clip) < num_frames and clip:
            clip.append(clip[-1])
    clip = np.stack(clip).astype(np.float32) / 255.0          # (T, H, W, C)
    clip = torch.from_numpy(clip).permute(3, 0, 1, 2)          # (C, T, H, W)
    mean = torch.tensor(KINETICS_MEAN).view(3, 1, 1, 1)
    std = torch.tensor(KINETICS_STD).view(3, 1, 1, 1)
    clip = (clip - mean) / std
    return clip.unsqueeze(0)  # (1, C, T, H, W)

def sample_detection_frames(video_path, start_frame, end_frame, fps, stride_seconds=1.0):
    stride_frames = max(1, int(round(fps * stride_seconds)))
    indices = list(range(start_frame, end_frame, stride_frames))
    return read_frames(video_path, indices)

"""## Step 6 - Per-segment inference

For each segment:
1. Run Stage 2 on the 16-frame clip -> top-1 action label + confidence.
2. Run Track 1 on ~1 fps sampled frames -> per-class max confidence + how many sampled frames it appeared in.
3. Run Track 2 the same way, filtered to context classes only.
"""

def aggregate_detections(model, frames_dict, keep_class_ids=None, conf_threshold=0.35):
    agg = {}  # class_name -> {'max_conf': float, 'frame_hits': int}
    for frame in frames_dict.values():
        results = model.predict(frame, conf=conf_threshold, verbose=False)[0]
        seen_this_frame = set()
        for box in results.boxes:
            cls_id = int(box.cls.item())
            if keep_class_ids is not None and cls_id not in keep_class_ids:
                continue
            cls_name = model.names[cls_id]
            conf = float(box.conf.item())
            entry = agg.setdefault(cls_name, {'max_conf': 0.0, 'frame_hits': 0})
            entry['max_conf'] = max(entry['max_conf'], conf)
            seen_this_frame.add(cls_name)
        for cls_name in seen_this_frame:
            agg[cls_name]['frame_hits'] += 1
    return agg

def run_segment(video_path, start_frame, end_frame, fps):
    # Stage 2 - action recognition
    clip = sample_action_recognition_clip(video_path, start_frame, end_frame).to(device)
    with torch.no_grad():
        logits = stage2_model(clip)
        probs = torch.softmax(logits, dim=1)[0]
        top_idx = int(torch.argmax(probs).item())

    # Sample frames once, reuse for both detectors
    det_frames = sample_detection_frames(video_path, start_frame, end_frame, fps)

    track1_dets = aggregate_detections(track1_model, det_frames)
    track2_dets = aggregate_detections(track2_model, det_frames, keep_class_ids=track2_class_ids)

    return {
        'action_label': ACTION_CLASSES[top_idx],
        'action_confidence': round(float(probs[top_idx]), 4),
        'track1_detections': track1_dets,
        'track2_detections': track2_dets,
    }

