def preprocess_action_frame(frame_rgb):
    frame = cv2.resize(frame_rgb, (128, 128))
    top, left = (128 - 112) // 2, (128 - 112) // 2
    return frame[top:top + 112, left:left + 112]

def build_action_clip(buffer_frames, num_frames=16):
    if not buffer_frames:
        return None
    indices = np.linspace(0, len(buffer_frames) - 1, num_frames).astype(int)
    clip = [preprocess_action_frame(buffer_frames[i]) for i in indices]
    clip = np.stack(clip).astype(np.float32) / 255.0
    clip = torch.from_numpy(clip).permute(3, 0, 1, 2)
    mean = torch.tensor(KINETICS_MEAN).view(3, 1, 1, 1)
    std = torch.tensor(KINETICS_STD).view(3, 1, 1, 1)
    clip = (clip - mean) / std
    return clip.unsqueeze(0)

